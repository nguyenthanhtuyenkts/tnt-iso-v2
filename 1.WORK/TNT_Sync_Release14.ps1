param([switch]$Check)
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$source = Join-Path $root '0.RELEASE'
$target = Join-Path $root '00.RELEASE 14'
$utf8 = New-Object System.Text.UTF8Encoding($false, $true)
$ascii = [System.Text.Encoding]::ASCII
$pending = @()
foreach ($file in Get-ChildItem -LiteralPath $source -Recurse -File) {
    # DWG/BAK and compiled VLX require separate format/runtime validation.
    if ($file.Extension -in @('.dwg', '.bak', '.vlx')) { continue }
    $relative = $file.FullName.Substring($source.Length + 1)
    $dest = Join-Path $target $relative
    $bytes = [IO.File]::ReadAllBytes($file.FullName)
    if ($file.Extension -ieq '.lsp') {
        $body = $utf8.GetString($bytes).TrimStart([char]0xFEFF)
        # ASCII source is independent of the Windows ANSI code page used by 2014.
        $body = $body.Replace([char]0x0111, 'd').Replace([char]0x0110, 'D')
        $body = $body.Normalize([Text.NormalizationForm]::FormD)
        $body = [regex]::Replace($body, '\p{Mn}', '')
        $body = $body.Replace([string][char]0x2192, '->')
        $body = [regex]::Replace($body, '[^\x00-\x7F]', '?')
        # These direct setters otherwise abort the enclosing shortcut on 2014.
        $body = $body.Replace('(setvar "DIMLAYER" ".")', '(princ)')
        $body = $body.Replace('(setvar "DIMLAYER" "....22_TNT_N_DIMENSION")', '(princ)')
        # Unsupported preferences are omitted; existing guarded settings remain.
        $body = [regex]::Replace($body, '(?m)^\s*\(TNT:SYSTEM_SETTING "(?:DIMLAYER|TEXTLAYER|MLEADERLAYER|COLORTHEME|STARTMODE|SELECTIONEFFECT|TEXTALLCAPS)"[^\r\n]*', '')
        if ($file.Name -eq 'TNT_PACKAGE_11_SHORTCUT.lsp') {
            $pattern = '(?s);;; Use the current command version.*?\(defun c:RR \(/\).*?\(princ\)\s*\)'
            $replacement = @'
;;; AutoCAD 2014: create a rectangle, then convert it using REVCLOUD Object.
(defun c:RR (/ *error* a b old before rect)
  (setq old (getvar "CMDECHO"))
  (defun *error* (msg)
    (setvar "CMDECHO" old)
    (if (and msg (not (wcmatch (strcase msg) "*CANCEL*,*QUIT*,*BREAK*")))
      (princ (strcat "\n[TNT] RR: " msg)))
    (princ))
  (if (and (setq a (getpoint "\nFirst corner: "))
           (setq b (getcorner a "\nOpposite corner: ")))
    (progn
      (setvar "CMDECHO" 0)
      (setq before (entlast))
      (command "_.RECTANG" "_non" a "_non" b)
      (setq rect (entlast))
      (if (and rect (not (eq before rect)))
        (progn (initcommandversion 1) (command "_.REVCLOUD" "_Object" rect "_No")))))
  (setvar "CMDECHO" old)
  (princ))
'@
            if (-not [regex]::IsMatch($body, $pattern)) { throw 'RR source changed: review the AutoCAD 2014 adaptation.' }
            $body = [regex]::Replace($body, $pattern, [System.Text.RegularExpressions.MatchEvaluator]{param($m) $replacement})
        }
        $body = ";;; Generated by 1.WORK/TNT_Sync_Release14.ps1 - AutoCAD 2014 ASCII edition.`r`n" + $body
        $bytes = $ascii.GetBytes($body)
    }
    $same = (Test-Path -LiteralPath $dest) -and
        ([Convert]::ToBase64String([IO.File]::ReadAllBytes($dest)) -ceq [Convert]::ToBase64String($bytes))
    if (-not $same) {
        $pending += $relative
        if (-not $Check) {
            [IO.Directory]::CreateDirectory((Split-Path $dest -Parent)) | Out-Null
            [IO.File]::WriteAllBytes($dest, $bytes)
        }
    }
}
if ($Check -and $pending.Count) { throw ('Release14 out of sync: ' + ($pending -join ', ')) }
Write-Output ("Release14: {0} file(s) {1}." -f $pending.Count, $(if ($Check) {'pending'} else {'updated'}))
